package ru.computershik.troubadour

import android.app.Application
import android.content.Context
import android.os.Build
import ru.computershik.troubadour.net.Auth
import ru.computershik.troubadour.net.NSig
import ru.computershik.troubadour.net.PoToken
import ru.computershik.troubadour.net.WebAuth
import ru.computershik.troubadour.ui.ImageLoader
import ru.computershik.troubadour.ui.RoundedImage

/**
 * То, что в оригинале делает `YTAppDelegate` в `didFinishLaunching`.
 *
 * Здесь это Application, а не Activity, и разница существенная: Activity
 * пересоздаётся при повороте и при возврате из фона, а вход, веб-сессия
 * и подготовка PO-токена должны случиться ровно один раз за запуск
 * процесса. В оригинале это выходило само собой — делегат приложения там
 * один, — а на Android за этим надо следить.
 */
class App : Application() {

    companion object {

        /**
         * Контекст приложения одним полем.
         *
         * Утечки здесь нет: это контекст самого процесса, он живёт ровно
         * столько же, сколько статическое поле. Обычный экранный контекст
         * так держать было бы нельзя.
         *
         * Нужен он потому, что перенесённый код зовёт настройки, значки
         * и переводы отовсюду, включая места, куда контекст неоткуда взять:
         * разбор ответа сервера на фоновом потоке, статические таблицы
         * качества, форматирование чисел. В оригинале ничего подобного
         * не требовалось — `NSUserDefaults` и `NSBundle` спрашиваются
         * без предъявления чего бы то ни было.
         */
        @Volatile
        @JvmStatic
        var context: Context? = null
            private set

        fun require(): Context =
            context ?: throw IllegalStateException("Приложение ещё не поднялось")
    }

    override fun onCreate() {
        super.onCreate()

        context = applicationContext

        // Журнал первым: всё, что ниже, уже пишет в него.
        Log.attach(filesDir)

        // Обрыв записывается и в готовой сборке — иначе он остаётся немым.
        Log.attachCrashHandler()

        /**
         * Дальше — только в нашем процессе.
         *
         * `Application` заводится в каждом процессе приложения, а их у нас
         * два: свой и тот, где живёт решатель PO-токена. Всё, что ниже,
         * относится к разговору с пользователем — вход, веб-сессия,
         * расшифровка `n`, — и в процессе решателя было бы вторым,
         * никому не нужным заходом: лишний веб-вид, лишние запросы
         * и удвоенная черта запуска в журнале.
         *
         * Журнал и запись обрыва при этом заведены выше, до проверки:
         * они нужны обоим, иначе решатель молчал бы о себе.
         */
        if (!ours()) {
            Log.now { "[YouTube/PO] Процесс решателя поднят" }

            return
        }

        /**
         * Черта запуска.
         *
         * Журнал дописывается, и в одном файле лежат записи от разных
         * сборок подряд. Версия между ними не меняется, поэтому отделять
         * приходилось по времени и на глаз. Теперь граница видна сразу,
         * и рядом с ней сказано, чем именно эти строки написаны и на чём.
         */
        Log.now { "[YouTube] ──────── запуск ────────" }
        Log.now {
            "[YouTube] Troubadour ${BuildConfig.VERSION_NAME}, " +
                "сборка ${BuildConfig.BUILD_STAMP}"
        }
        Log.now {
            "[YouTube] ${Build.MANUFACTURER} ${Build.MODEL}, " +
                "Android ${Build.VERSION.RELEASE} (API ${Build.VERSION.SDK_INT}), " +
                "плотность ${resources.displayMetrics.density}, " +
                "экран ${resources.displayMetrics.widthPixels}×" +
                "${resources.displayMetrics.heightPixels}"
        }

        /**
         * SIGPIPE, ради которого в оригинале стоял `signal(SIGPIPE, SIG_IGN)`,
         * здесь не нужен вовсе: в JVM запись в закрытый сокет — это
         * исключение, а не сигнал, и процесс от неё не умирает.
         *
         * Вместе с ним отпала и половина причины, по которой этот сигнал
         * там ловили: HLS-прокси на 127.0.0.1 у нас нет — ExoPlayer берёт
         * фрагменты прямо у нашего источника данных.
         */

        // Поднимаем сохранённый вход до того, как экраны спросят о нём.
        Auth.restore()

        /**
         * И веб-сессию — тем же порядком и по той же причине.
         *
         * Куки, положенные веб-видом при входе в браузере, живут в общем
         * хранилище, пока приложение работает, но до следующего запуска
         * доходят не всегда. Свой запас поднимаем сами и до первых запросов:
         * иначе первый же ответ `/player` придёт с проверкой «вы не бот»,
         * хотя человек давно вошёл.
         */
        WebAuth.restoreSession()

        /**
         * Подготовка PO-токена и разбор `player.js` начинаются сразу и идут
         * своим чередом: они стоят нескольких секунд, а нужны к первому же
         * ролику. Ждать их никто не будет — запрос потоков уйдёт и без
         * токена, просто с ним он проходит стену «подтвердите, что вы не бот».
         *
         * Веб-вид, в котором крутится программа botguard, поднимается
         * спрятанным и остаётся жить: чеканка потом занимает миллисекунды.
         *
         * Заводит его **не здесь**, а `MainActivity`, и не из опрятности:
         * виду нужно окно. Программа проверки размечает работу по кадрам
         * отрисовки, а до появления окна рисовать не на чем — начатая
         * тут подготовка молча стояла бы до самого сторожа. Application
         * поднимается раньше любого окна, поэтому здесь остаётся только
         * расшифровка `n`, которой окно не нужно.
         */
        NSig.prepare()
    }

    /**
     * Наш ли это процесс — тот, что разговаривает с пользователем.
     *
     * Имя процесса система прямо не отдаёт, поэтому ищем себя по номеру
     * среди работающих. Побочные процессы зовутся `пакет:имя`, наш —
     * просто именем пакета. Не нашли себя вовсе — считаем, что наш:
     * так поведение остаётся прежним, а не отключается целиком.
     */
    private fun ours(): Boolean {
        val manager = getSystemService(ACTIVITY_SERVICE) as? android.app.ActivityManager
            ?: return true

        val mine = android.os.Process.myPid()

        val running = try {
            manager.runningAppProcesses
        } catch (error: Throwable) {
            null
        } ?: return true

        for (process in running) {
            if (process.pid == mine) {
                return process.processName == packageName
            }
        }

        return true
    }

    /**
     * Система просит потесниться — отдаём оба кеша картинок: сами превью
     * и готовые скруглённые кадры.
     *
     * На слабом устройстве система молча просит освободиться, а если
     * не помогло — снимает приложение. Со стороны это неотличимо
     * от падения по своей вине.
     */
    override fun onLowMemory() {
        super.onLowMemory()

        Log.d { "[YouTube/Память] Система просит освободить память" }

        ImageLoader.trim()
        RoundedImage.trimFrames()
    }

    /**
     * Уходя в фон, отдаём картинки сами, не дожидаясь просьбы.
     *
     * В фоне нас держат только ради звука, а память меряют по всему занятому.
     * Разобранные превью — самое крупное, что у нас есть, и на телефоне их
     * набирается на десятки мегабайт. Кто занимает больше, того система
     * и снимает первым; снятое приложение при возврате начинает всё заново.
     */
    override fun onTrimMemory(level: Int) {
        super.onTrimMemory(level)

        if (level < TRIM_MEMORY_BACKGROUND) {
            return
        }

        ImageLoader.trim()
        RoundedImage.trimFrames()

        /**
         * Заодно освежаем запас веб-сессии: Google подменяет куки по ходу
         * работы, и отложенные при входе к следующему запуску могли
         * устареть.
         */
        WebAuth.keepSession()

        Log.d { "[YouTube/Память] Ушли в фон — картинки отданы" }
    }
}
